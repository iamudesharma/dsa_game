class SectionHeading extends StatelessWidget {
  const SectionHeading({required this.title, this.trailing, this.icon, super.key});

  final String title;
  final Widget? trailing;
  final IconData? icon;

  @override
  Widget build(BuildContext context) {
    final colors = context.gameColors;
    return Row(
      children: [
        if (icon != null) ...[
          Icon(icon, size: 12, color: colors.muted),
          const SizedBox(width: 5),
        ],
        Text(
          title.toUpperCase(),
          style: TextStyle(
            fontSize: 9,
            fontWeight: FontWeight.w900,
            letterSpacing: 1.3,
            color: colors.muted,
          ),
        ),
        const Spacer(),
        ?trailing,
      ],
    );
  }
}

